def env_sources():
    """key -> (file, section, env var names, comment description), in source order"""
    from ofscraper.utils.of_env import get_all_configs

    keys = set(get_all_configs())
    found = {}
    base = ROOT / "ofscraper/utils/of_env/values"
    for path in sorted(base.rglob("*.py")):
        if "test" in path.relative_to(base).parts:
            continue
        src = path.read_text(encoding="utf-8")
        lines = src.splitlines()
        tree = ast.parse(src)
        for fn in [n for n in tree.body if isinstance(n, ast.FunctionDef)]:
            stmts = []
            for node in ast.walk(fn):
                if isinstance(node, ast.Assign):
                    for t in node.targets:
                        if (
                            isinstance(t, ast.Subscript)
                            and getattr(t.value, "id", "") == "config"
                            and isinstance(t.slice, ast.Constant)
                        ):
                            stmts.append((node.lineno, node.end_lineno, t.slice.value))
            stmts.sort()
            prev_end = fn.body[0].end_lineno
            section = ""
            for lineno, end, key in stmts:
                window = lines[prev_end:end]
                for line in window:
                    m = re.match(r"\s*#+\s*-{2,}\s*(.+?)\s*-{2,}\s*$", line)
                    if m:
                        section = m.group(1)
                if key not in found and key in keys:
                    text = "\n".join(window)
                    envs = list(dict.fromkeys(re.findall(r'getenv\(\s*"([A-Za-z0-9_]+)"', text)))
                    m = re.search(r"#\s*" + re.escape(key) + r"\s*:\s*(.+)", text)
                    found[key] = (rel(path), section, envs, m.group(1).strip() if m else "")
                prev_end = max(prev_end, end)
    return found


def direct_env():
    """environment variables read with os.getenv outside of_env/values: name -> (file, default)"""
    found = {}
    skip = ROOT / "ofscraper/utils/of_env/values"
    for path in sorted((ROOT / "ofscraper").rglob("*.py")):
        if skip in path.parents:
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)):
                continue
            func = node.func
            is_getenv = func.attr == "getenv" and getattr(func.value, "id", "") == "os"
            is_get = (
                func.attr == "get"
                and isinstance(func.value, ast.Attribute)
                and func.value.attr == "environ"
            )
            if not (is_getenv or is_get) or not node.args:
                continue
            first = node.args[0]
            if not (isinstance(first, ast.Constant) and isinstance(first.value, str)):
                continue
            default = ast.unparse(node.args[1]) if len(node.args) > 1 else "None"
            found.setdefault(first.value, (rel(path), default))
    return dict(sorted(found.items()))


def env_description(key, comment, notes):
    if key in notes.ENV:
        return notes.ENV[key].strip()
    if comment:
        return comment
    for pattern, text in notes.ENV_PATTERNS:
        if re.fullmatch(pattern, key):
            return text.strip()
    return ""


