def module_functions(path):
    tree = ast.parse(pathlib.Path(path).read_text(encoding="utf-8"))
    return {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}


def option_definitions():
    """flag string -> set of files that define a click option using it"""
    found = {}
    for base in ("ofscraper/utils/args", "ofscraper/commands"):
        for path in sorted((ROOT / base).rglob("*.py")):
            tree = ast.parse(path.read_text(encoding="utf-8"))
            for node in ast.walk(tree):
                if not isinstance(node, ast.Call):
                    continue
                func = node.func
                name = func.attr if isinstance(func, ast.Attribute) else getattr(func, "id", "")
                if name != "option":
                    continue
                flags = {
                    a.value
                    for a in node.args
                    if isinstance(a, ast.Constant) and isinstance(a.value, str)
                }
                for flag in flags:
                    found.setdefault(flag, set()).add(rel(path))
    return found


def config_getter_map():
    """config key path -> (getter name, module file) from schema.py"""
    schema_path = ROOT / "ofscraper/utils/config/schema.py"
    fn = module_functions(schema_path)["get_current_config_schema"]
    modules = {
        "data": "ofscraper/utils/config/data.py",
        "common_paths": "ofscraper/utils/paths/common.py",
    }
    result = {}

    def walk(node, prefix):
        for key, value in zip(node.keys, node.values):
            if isinstance(key, ast.Constant):
                name = key.value
            else:  # the profile key, named by the mainProfile default
                name = "main_profile"
            path = f"{prefix}{name}"
            if isinstance(value, ast.Dict):
                walk(value, path + ".")
            elif isinstance(value, ast.Call) and isinstance(value.func, ast.Attribute):
                owner = value.func.value.id
                result[path] = (value.func.attr, modules[owner])

    for node in ast.walk(fn):
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Dict):
            walk(node.value, "")
            break
    return result


def getter_details(getter, module_file, key_path):
    """(environment defaults read, older config keys read) by a config getter"""
    fn = module_functions(ROOT / module_file).get(getter)
    envs, keys = [], []
    if fn is None:
        return envs, keys
    own = key_path.split(".")
    for node in ast.walk(fn):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
            continue
        args = [a.value for a in node.args if isinstance(a, ast.Constant) and isinstance(a.value, str)]
        if not args:
            continue
        if node.func.attr == "getattr" and getattr(node.func.value, "id", "") == "of_env":
            envs.append(args[0])
        elif node.func.attr == "get":
            keys.append(args[0])
    # the key's own name (and its section) aren't "older" keys
    older = sorted({k for k in keys if k not in own})
    return sorted(set(envs)), older


def settings_links(not_merged=()):
    """CLI dest -> config getters it's merged with, from settings.merged_settings"""
    fn = module_functions(ROOT / "ofscraper/utils/settings.py")["merged_settings"]
    links = {}
    config_only = set()
    for node in fn.body:
        if not isinstance(node, ast.Assign):
            continue
        dests, getters = set(), set()
        for sub in ast.walk(node.value):
            if isinstance(sub, ast.Attribute) and getattr(sub.value, "id", "") == "args":
                dests.add(sub.attr)
            if (
                isinstance(sub, ast.Call)
                and isinstance(sub.func, ast.Attribute)
                and getattr(sub.func.value, "id", "") == "config_data"
            ):
                getters.add(sub.func.attr)
        for dest in dests - set(not_merged):
            links.setdefault(dest, set()).update(getters)
        if getters and not dests:
            config_only.update(getters)
    return links, config_only


