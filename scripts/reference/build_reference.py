def database_schema():
    """table -> (columns, indexes) of a new user_data.db after migrations"""
    import ofscraper.db.operations as operations
    import ofscraper.db.transition as transition

    # the app's run() helper uses the current event loop; give it one, since
    # asking for it when there's none is deprecated
    loop = asyncio.new_event_loop()
    asyncio.set_event_loop(loop)
    # the pre-migration backup reads the real profile's config and cache;
    # a throwaway database needs no backup
    backup = transition.create_backup_transition
    transition.create_backup_transition = lambda *args, **kwargs: None
    with tempfile.TemporaryDirectory() as tmp:
        path = pathlib.Path(tmp, "user_data.db")
        try:
            operations.create_tables(model_id=1, username="a_creator", db_path=path)
            transition.modify_tables(model_id=1, username="a_creator", db_path=path)
        finally:
            transition.create_backup_transition = backup
            asyncio.set_event_loop(None)
            loop.close()
        tables = {}
        with contextlib.closing(sqlite3.connect(path)) as conn:
            names = [
                r[0]
                for r in conn.execute(
                    "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
                )
            ]
            for name in names:
                columns = [
                    {"name": r[1], "type": r[2], "notnull": bool(r[3]), "default": r[4], "pk": bool(r[5])}
                    for r in conn.execute(f"PRAGMA table_info('{name}')")
                ]
                indexes = []
                for idx in conn.execute(f"PRAGMA index_list('{name}')"):
                    cols = [r[2] for r in conn.execute(f"PRAGMA index_info('{idx[1]}')")]
                    indexes.append({"unique": bool(idx[2]), "origin": idx[3], "columns": cols})
                tables[name] = (columns, indexes)
    return tables


def render_database(notes):
    tables = database_schema()
    out = [HEADER, "# Database reference (`user_data.db`)\n\n"]
    out.append(notes.DATABASE_NOTES.strip() + "\n\n")
    out.append(
        "The tables and columns below are what a new database has after"
        " `ofscraper.db.operations.create_tables` and `ofscraper.db.transition.modify_tables`"
        " run. The create statements are in `ofscraper/db/operations_/`.\n\n"
        "Tables: " + ", ".join(f"[`{n}`](#{anchor(n)})" for n in tables) + ".\n\n"
    )
    for name, (columns, indexes) in tables.items():
        note = notes.TABLES[name]
        out.append(f"## `{name}`\n\n")
        out.append(note["summary"].strip() + "\n\n")
        out.append(f"**Written by:** {note['written_by'].strip()}\n\n")
        uniques = [i for i in indexes if i["unique"]]
        if uniques:
            out.append(
                "**Unique:** "
                + "; ".join("(" + ", ".join(f"`{c}`" for c in i["columns"]) + ")" for i in uniques)
                + "\n\n"
            )
        out.append("| Column | Type | Not null | Default | Description |\n|---|---|---|---|---|\n")
        for col in columns:
            pk = " (primary key)" if col["pk"] else ""
            default = "" if col["default"] is None else code(col["default"])
            out.append(
                f"| `{col['name']}`{pk} | {col['type'] or ''} | {'yes' if col['notnull'] else ''}"
                f" | {cell(default)} | {cell(note['columns'][col['name']].strip())} |\n"
            )
        out.append("\n")
    return "".join(out)


