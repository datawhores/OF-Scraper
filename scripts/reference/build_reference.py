def rel(path):
    return pathlib.Path(path).resolve().relative_to(ROOT).as_posix()


def normalise(text):
    """Replace this machine's home directory so the output is the same everywhere."""
    home = pathlib.Path.home()
    for form in (str(home), home.as_posix()):
        while form and form in text:
            start = text.index(form)
            end = start + len(form)
            # the rest of the path, up to a quote or whitespace
            m = re.match(r"[^'\"\s,\]\)]*", text[end:])
            tail = m.group(0).replace("\\\\", "/").replace("\\", "/")
            text = text[:start] + "{home_directory}" + tail + text[end + len(m.group(0)) :]
    return text


def normalise_value(value):
    if isinstance(value, str):
        return normalise(value)
    if isinstance(value, pathlib.PurePath):
        return normalise(str(value))
    if isinstance(value, (list, tuple)):
        return type(value)(normalise_value(v) for v in value)
    if isinstance(value, dict):
        return {k: normalise_value(v) for k, v in value.items()}
    return value


def value_text(value, style="python"):
    """A short, deterministic rendering of a default value."""
    value = normalise_value(value)
    if isinstance(value, (set, frozenset)):
        value = sorted(value, key=str)
    if isinstance(value, dict) and len(json.dumps(value, default=str)) > 70:
        return f"a dict of {len(value)} entries (see the source)"
    if isinstance(value, (list, tuple)) and len(json.dumps(value, default=str)) > 70:
        return f"a list of {len(value)} items (see the source)"
    if style == "json":
        try:
            text = json.dumps(value)
        except TypeError:
            text = repr(value)
    else:
        text = repr(value)
    return code(normalise(text))


def code(text):
    text = str(text).replace("\n", " ")
    ticks = "``" if "`" in text else "`"
    pad = " " if ticks == "``" else ""
    return f"{ticks}{pad}{text}{pad}{ticks}"


def cell(text):
    return str(text).replace("\n", " ").replace("|", "\\|")


def clean_help(text):
    if not text:
        return ""
    text = text.replace("\b", " ")
    return re.sub(r"\s+", " ", text).strip()


def anchor(text):
    """GitHub's heading anchor for a heading made of ``text``."""
    text = text.strip().lower()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


