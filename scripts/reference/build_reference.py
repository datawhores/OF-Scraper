def type_text(param):
    import click

    t = param.type
    if getattr(param, "is_flag", False) and not getattr(param, "count", False):
        text = "flag"
    elif isinstance(t, click.Choice):
        text = "one of " + ", ".join(code(c) for c in t.choices)
    elif isinstance(t, click.types.FuncParamType):
        text = f"text, parsed by `{t.func.__name__}`"
    elif isinstance(t, click.File):
        text = "file"
    elif isinstance(t, click.Path):
        text = "path"
    elif getattr(t, "choices", None):  # the app's own multi-choice types
        text = "one or more of " + ", ".join(code(c) for c in t.choices)
    else:
        text = getattr(t, "name", type(t).__name__)
    if param.multiple:
        text += "; repeatable"
    return text


def default_text(param):
    default = param.default
    if default is None or "UNSET" in repr(default) or "Sentinel" in repr(default):
        return "none"
    if callable(default):
        return "computed when parsed"
    if getattr(param, "is_flag", False) and default is False:
        return "off"
    return value_text(default)


def option_heading(param):
    longs = [o for o in param.opts if o.startswith("--")]
    return (longs or param.opts)[0]


def collect_options():
    """unique options with the commands that accept them, in group order"""
    commands = command_objects()
    options = {}
    for cmd_name, cmd in commands.items():
        group_of = {}
        for group in getattr(cmd, "option_groups", []):
            for opt in group.options:
                group_of[id(opt)] = group.title
        for param in cmd.params:
            key = (param.name, tuple(param.opts), tuple(param.secondary_opts))
            entry = options.setdefault(
                key,
                {"param": param, "commands": [], "group": group_of.get(id(param), "Other options")},
            )
            entry["commands"].append(cmd_name)
    return list(options.values())


def command_label(name):
    return "main program" if name == "" else f"`{name}`"


