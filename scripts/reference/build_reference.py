def stale_files(rendered=None):
    rendered = rendered or render_all()
    stale = []
    for name, text in rendered.items():
        path = OUT / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(name)
    return stale


def main(check):
    rendered = render_all()
    if check:
        stale = stale_files(rendered)
        for name in stale:
            print(f"reference/{name} is out of date; run scripts/reference/build_reference.py")
        return 1 if stale else 0
    OUT.mkdir(exist_ok=True)
    for name, text in rendered.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote reference/{name}")
    return 0


