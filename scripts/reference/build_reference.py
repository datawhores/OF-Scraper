@contextlib.contextmanager
def clean_environment():
    """Drop OFSC_* variables and bare setting names so defaults are the built-in ones."""
    from ofscraper.utils.of_env import get_all_configs

    saved = dict(os.environ)
    keys = set(get_all_configs(forced=True))
    for name in list(os.environ):
        if name.startswith("OFSC_") or name in keys:
            del os.environ[name]
    get_all_configs(forced=True)
    try:
        yield
    finally:
        os.environ.clear()
        os.environ.update(saved)
        get_all_configs(forced=True)


